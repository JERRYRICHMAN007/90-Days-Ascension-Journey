// - Proof of work (behind-the-scenes, processes)
// - Process sharing (how-to, frameworks)
// - Results or lessons (wins, transformations, case studies)
// - Soft monetization signals (hints, CTAs, no hard selling)

// Get execution tasks for a specific week and day
export function getExecutionTasks(weekNum, dayIndex, brand = 'both') {
  // Week 1 is testing, start from Week 2
  const actualWeek = weekNum - 1; // Week 2 becomes index 1
  
  let plan;
  if (actualWeek === 1) {
    plan = weeklyExecutionPlan.week2;
  } else if (actualWeek === 2) {
    plan = weeklyExecutionPlan.week3;
  } else {
    plan = weeklyExecutionPlan.week4Plus;
  }

  const dayNames = ['sunday', 'monday', 'tuesday', 'wednesday', 'thursday', 'friday', 'saturday'];
  const dayName = dayNames[dayIndex];
  const dayPlan = plan[dayName];

  if (!dayPlan) return { personal: [], company: [] };

  // Support both old keys (ryxen/havenx) and new keys (personal/company)
  // Old: ryxen = personal brand, havenx = company brand
  // New: personal = _richman.oo7, company = _ryxen.oo7
  if (brand === 'ryxen' || brand === 'personal') {
    return { personal: dayPlan.ryxen || dayPlan.personal || [], company: [] };
  } else if (brand === 'havenx' || brand === 'company') {
    return { personal: [], company: dayPlan.havenx || dayPlan.company || [] };
  }

  // Return both brands
  return { 
    personal: dayPlan.ryxen || dayPlan.personal || [], 
    company: dayPlan.havenx || dayPlan.company || [] 
  };
}

